export type PixelIconName = keyof typeof ICONS

type Props = {
  name: PixelIconName
  /** Rendered height in px (width follows the grid aspect). */
  size?: number
  className?: string
  color?: string
}

export function PixelIcon({ name, size = 28, className, color = 'currentColor' }: Props) {
  const rows = ICONS[name]
  const h = rows.length
  const w = rows[0]!.length
  const rects: ReactElement[] = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} />)
    }
  })
  return (
    <svg
      className={className}
      viewBox={`0 0 ${w} ${h}`}
      width={(size * w) / h}
      height={size}
      fill={color}
      shapeRendering="crispEdges"
      aria-hidden
    >
      {rects}
    </svg>
  )
}
